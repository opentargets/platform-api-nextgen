(
  SELECT
    e.id AS id,
    e.score AS score,
    e.diseaseId AS diseaseId,
    dictGet('disease_names', 'name', e.diseaseId) AS diseaseName,
    e.diseaseFromSource AS diseaseFromSource,
    e.targetId AS targetId,
    dictGet('target_symbols', 'approvedSymbol', e.targetId) AS targetApprovedSymbol,
    e.targetFromSourceId AS targetFromSourceId,
    e.releaseVersion AS releaseVersion,
    arrayFilter(u -> u != '', arrayMap(u -> ifNull(u.url, ''), e.urls)) AS urls,
    e.directionOnTarget AS directionOnTarget,
    e.directionOnTrait AS directionOnTrait,
    e.allelicRequirements AS allelicRequirements,
    e.studyId AS studyId,
    e.ancestry AS ancestry,
    e.ancestryId AS ancestryId,
    e.resourceScore AS resourceScore,
    e.cohortId AS cohortId,
    e.projectId AS projectId,
    e.statisticalMethod AS statisticalMethod,
    e.statisticalMethodOverview AS statisticalMethodOverview,
    e.studyCases AS studyCases,
    e.studyCasesWithQualifyingVariants AS studyCasesWithQualifyingVariants,
    e.studySampleSize AS studySampleSize,
    e.oddsRatio AS oddsRatio,
    e.oddsRatioConfidenceIntervalLower AS oddsRatioConfidenceIntervalLower,
    e.oddsRatioConfidenceIntervalUpper AS oddsRatioConfidenceIntervalUpper,
    e.beta AS beta,
    e.betaConfidenceIntervalLower AS betaConfidenceIntervalLower,
    e.betaConfidenceIntervalUpper AS betaConfidenceIntervalUpper,
    e.pValueMantissa AS pValueMantissa,
    e.pValueExponent AS pValueExponent,
    e.literature AS literature
  FROM evidence AS e
)
